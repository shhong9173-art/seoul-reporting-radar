def public_questions(kind,source=None):
    values=list(QUESTIONS.get(kind,DEFAULT))
    if isinstance(source,dict):
        receipt=source.get("receiptNo")
        if isinstance(receipt,str) and re.fullmatch(r"20\d{12}",receipt):
            # Only expose an official filing reference, not an inferred story.
            values[0]="DART "+receipt+" · "+values[0]
    return values


def validate_public_policy():
    forbidden=(
       "생산·조달계획","공급사 변경 계획","내부 의사결정",
       "어떤 대응을 준비","상용화 계획","양산·상용화 계획",
       "물량·기간·단가와 실제 생산능력 투입",
       "신규 고객 또는 신규 시장 진입을 의미",
       "공급망 변경을 준비",
    )
    for kind,questions in list(QUESTIONS.items())+[("default",DEFAULT)]+list(LEAD_QUESTIONS.items())+[("lead-default",LEAD_DEFAULT)]:
        if not 2<=len(questions)<=3 or any(not q.endswith("?") for q in questions):
            raise ValueError("invalid_public_questions_"+kind)
        for q in questions:
            if any(term in q for term in forbidden):
                raise ValueError("nonpublic_question_"+kind)
    return True
